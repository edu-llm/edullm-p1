#!/usr/bin/env python3
"""Copy a finished W&B run into another project, then check the copy row for row.

It copies the source run's config, full history (every logged key at every
step, training metrics included), summary, and its small artifacts (eval,
task-loss, progress and method-state files under ``--max-artifact-mb``). The
model checkpoint is not copied; its artifact name and the source run's URL are
recorded in the copy's config (``clone_source``) and notes instead. W&B's own
``run-<id>-history`` artifact is regenerated by W&B for the copy.

The copy keeps the source run's name and group, and by default its run id, so
re-running is safe: an existing complete copy is only re-verified, and an
existing incomplete one is left alone with an error.

Used to put the static LightGBM L40S run (``eduLLM/skillit/zgmte13g``, Slurm
job 1744338) into ``eduLLM/mixlaw-new`` next to the other static 370M runs:

    python clone_wandb_run.py --source eduLLM/skillit/zgmte13g \
        --dest-project mixlaw-new --source-note "Slurm job 1744338"
"""

from __future__ import annotations

import argparse
import datetime as dt
import math
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

import wandb

SYSTEM_KEYS = {"_step", "_runtime", "_timestamp"}
SKIP_ARTIFACT_TYPES = {"model", "wandb-history"}


def same(a: Any, b: Any) -> bool:
    if isinstance(a, float) and isinstance(b, float) and math.isnan(a) and math.isnan(b):
        return True
    return a == b


def history(run: Any) -> list[dict[str, Any]]:
    rows = [
        {k: v for k, v in row.items() if v is not None}
        for row in run.scan_history(page_size=1000)
    ]
    rows.sort(key=lambda row: row["_step"])
    return rows


def user_summary(run: Any) -> dict[str, Any]:
    return {k: v for k, v in run.summary._json_dict.items() if not k.startswith("_")}


def verify(api: wandb.Api, source: Any, dest_path: str, src_rows: list[dict[str, Any]]) -> bool:
    dest = api.run(dest_path)
    dst_rows: list[dict[str, Any]] = []
    for _ in range(40):  # W&B may take a little while to serve the finished history
        dest = api.run(dest_path)
        dst_rows = history(dest)
        if len(dst_rows) >= len(src_rows):
            break
        time.sleep(15)
    by_step = {row["_step"]: row for row in dst_rows}
    checks: list[tuple[str, bool, str]] = []

    checks.append(("history row count", len(dst_rows) == len(src_rows),
                   f"source {len(src_rows)}, copy {len(dst_rows)}"))
    macro_src = {r["_step"]: r["eval/macro_bpb"] for r in src_rows if "eval/macro_bpb" in r}
    macro_bad = [s for s, v in macro_src.items() if not same(by_step.get(s, {}).get("eval/macro_bpb"), v)]
    macro_dst = {r["_step"] for r in dst_rows if "eval/macro_bpb" in r}
    checks.append(("eval/macro_bpb at every source step", not macro_bad and macro_dst == set(macro_src),
                   f"{len(macro_src)} steps {sorted(macro_src)}; mismatched {macro_bad}"))

    cell_total = cell_bad = 0
    bad_examples: list[str] = []
    for row in src_rows:
        other = by_step.get(row["_step"], {})
        for key, value in row.items():
            if key in SYSTEM_KEYS:
                continue
            cell_total += 1
            if not same(other.get(key), value):
                cell_bad += 1
                if len(bad_examples) < 5:
                    bad_examples.append(f"step {row['_step']} {key}: {value!r} vs {other.get(key)!r}")
    extra = sum(1 for row in dst_rows for k in row if k not in SYSTEM_KEYS) - cell_total
    checks.append(("every non-system history cell", cell_bad == 0 and extra == 0,
                   f"{cell_total} cells, {cell_bad} mismatched, {extra} extra; {bad_examples}"))

    src_sum, dst_sum = user_summary(source), user_summary(dest)
    bpb_keys = sorted(k for k in src_sum if k.startswith("eval/bpb/"))
    bpb_bad = [k for k in bpb_keys if not same(dst_sum.get(k), src_sum[k])]
    checks.append(("summary eval/bpb/<label>", bool(bpb_keys) and not bpb_bad,
                   f"{len(bpb_keys)} keys; mismatched {bpb_bad}"))
    sum_bad = [k for k in src_sum if not same(dst_sum.get(k), src_sum[k])]
    checks.append(("summary, every user key", not sum_bad,
                   f"{len(src_sum)} keys; mismatched {sum_bad[:10]}"))

    print(f"\nVerification of {dest_path} (state={dest.state}) against {source.path}:")
    for name, ok, detail in checks:
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {detail}")
    ok = all(ok for _, ok, _ in checks)
    print(f"CLONE_VERIFY {'PASS' if ok else 'FAIL'}")
    return ok


def copy_artifacts(source: Any, run: Any, max_bytes: int) -> tuple[list[str], list[str], list[str]]:
    copied, skipped, failed = [], [], []
    with tempfile.TemporaryDirectory() as tmp:
        for i, art in enumerate(source.logged_artifacts()):
            label = f"{art.type} {art.name} ({art.size} bytes)"
            if art.type in SKIP_ARTIFACT_TYPES or art.size > max_bytes:
                skipped.append(label)
                continue
            try:
                name, _, _ = art.name.partition(":")
                local = Path(tmp) / f"{i:04d}"
                local.mkdir()
                if art.manifest is not None and art.manifest.entries:
                    art.download(root=str(local))
                new = wandb.Artifact(
                    name=name,
                    type=art.type,
                    description=art.description,
                    metadata={
                        **(art.metadata or {}),
                        "cloned_from": f"{source.entity}/{source.project}/{art.name}",
                    },
                )
                new.add_dir(str(local))
                aliases = [a for a in art.aliases if a != "latest"]
                logged = run.log_artifact(new, aliases=aliases or None)
                logged.wait()
                copied.append(f"{label} -> {logged.name} aliases={aliases}")
            except Exception as exc:  # noqa: BLE001 - report every artifact that did not copy
                failed.append(f"{label}: {type(exc).__name__}: {exc}")
    return copied, skipped, failed


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", required=True, help="entity/project/run_id")
    ap.add_argument("--dest-project", required=True)
    ap.add_argument("--dest-entity", default=None, help="default: the source entity")
    ap.add_argument("--dest-id", default=None, help="default: the source run id")
    ap.add_argument("--source-note", default="", help="extra provenance for the notes, e.g. a Slurm job")
    ap.add_argument("--max-artifact-mb", type=float, default=50.0)
    args = ap.parse_args()

    api = wandb.Api(timeout=120)
    source = api.run(args.source)
    entity = args.dest_entity or source.entity
    dest_id = args.dest_id or source.id
    dest_path = f"{entity}/{args.dest_project}/{dest_id}"
    src_url = f"https://wandb.ai/{source.entity}/{source.project}/runs/{source.id}"
    print(f"source {source.path} name={source.name} state={source.state}")
    src_rows = history(source)
    print(f"source history: {len(src_rows)} rows, steps {src_rows[0]['_step']}..{src_rows[-1]['_step']}")

    try:
        existing = api.run(dest_path)
    except Exception as exc:  # noqa: BLE001 - the API raises several types for "not found"
        print(f"{dest_path} not found ({type(exc).__name__}); creating it")
        existing = None
    if existing is not None:
        print(f"{dest_path} already exists (state={existing.state}); verifying only")
        sys.exit(0 if verify(api, source, dest_path, src_rows) else 1)

    checkpoints = [
        f"{source.entity}/{source.project}/{a.name}"
        for a in source.logged_artifacts()
        if a.type == "model"
    ]
    today = dt.date.today().isoformat()
    note = f" ({args.source_note})" if args.source_note else ""
    notes = (
        f"Cloned from {source.entity}/{source.project}/{source.id}{note} by clone_wandb_run.py on "
        f"{today}. Original run: {src_url}. Model checkpoint not copied; see "
        f"{', '.join(checkpoints) or 'none'}."
    )
    config = dict(source.config)
    config["clone_source"] = {
        "run_path": f"{source.entity}/{source.project}/{source.id}",
        "url": src_url,
        "name": source.name,
        "state": source.state,
        "note": args.source_note,
        "checkpoint_artifacts": checkpoints,
        "cloned_on": today,
        "script": "experiments/skill-dag/mixlaw/clone_wandb_run.py",
    }
    run = wandb.init(
        entity=entity,
        project=args.dest_project,
        id=dest_id,
        name=source.name,
        group=source.group,
        tags=list(source.tags or []),
        notes=notes,
        config=config,
        resume="never",
    )
    for row in src_rows:
        payload = {k: v for k, v in row.items() if k not in SYSTEM_KEYS}
        run.log(payload, step=int(row["_step"]))
    for key, value in user_summary(source).items():
        run.summary[key] = value
    copied, skipped, failed = copy_artifacts(source, run, int(args.max_artifact_mb * 1024 * 1024))
    print(f"artifacts copied: {len(copied)}")
    for line in copied:
        print(f"  + {line}")
    print(f"artifacts not copied (checkpoint-sized or W&B-generated): {len(skipped)}")
    for line in skipped:
        print(f"  - {line}")
    print(f"artifacts that failed to copy: {len(failed)}")
    for line in failed:
        print(f"  ! {line}")
    wandb.finish(exit_code=0)
    ok = verify(api, source, dest_path, src_rows)
    sys.exit(0 if ok and not failed else 1)


if __name__ == "__main__":
    main()
